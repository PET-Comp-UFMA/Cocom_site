            <p>
                Decorridos quase 35 anos de sua fundação, o curso de Ciência da Computação evoluiu e hoje conta com 4
                laboratórios dedicados, exclusivamente, às atividades de ensino e 10 laboratórios de pesquisa (LABJEDI,
                LABMINT, LACMOR, LSDI, LAWS, LIDI, MECANET, NCA, Telemídia MA e VIPLAB), uma infraestrutura que atende
                atualmente cerca de 120 alunos distribuídos entre alunos de graduação, mestrado e doutorado. Além de
                contar com um Programa de Ensino Tutorial (PET), que atualmente possui 18 alunos, incluindo bolsistas e
                voluntários participando ativamente.
            </p>

            <p>
                O curso tem, ainda, o Programa de Pós-Graduação em Ciência da Computação (PPGCC), que oferta o mestrado
                em nível acadêmico e o Doutorado em Ciência da Computação em Associação UFMA/UFPI.
            </p>

