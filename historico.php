            <p>
                Atualmente, o curso tem cerca de 385 alunos matriculados e é responsável por ter formado ao longo desse
                tempo mais de 25 turmas. Uma parcela significativa desses bacharéis buscou o nível de Pós-graduação, com
                sucesso, em diversas instituições nacionais e internacionais, além da própria UFMA. A qualidade no
                ensino aqui desenvolvido também é reconhecida na sociedade, onde os principais cargos relacionados à TI
                no Maranhão, normalmente, são ocupados por egressos formados em Ciência da Computação na UFMA.
